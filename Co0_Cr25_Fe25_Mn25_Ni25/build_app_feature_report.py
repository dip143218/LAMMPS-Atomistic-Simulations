from __future__ import annotations
import csv
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent
R = 8.314462618

def read_rows(name: str) -> list[dict[str, str]]:
    with (ROOT / name).open(newline="", encoding="utf-8-sig") as handle:
        return list(csv.DictReader(handle))

features = {row["feature"]: row for row in read_rows("formula_features_Co0Cr25Fe25Mn25Ni25.csv")}
verification = {row["metric"]: row for row in read_rows("LAMMPS_verification_summary.csv")}

s_over_r = float(features["Sconf_over_R"]["value"])
mean_tm = float(features["mean_melting_point"]["value"])
dh_native = float(verification["DeltaHmix_elemental_reference"]["value"])
dh_fcc = float(verification["DeltaHmix_FCC_reference"]["value"])

def omega(delta_h_kj_mol: float) -> float:
    if delta_h_kj_mol == 0.0:
        return math.nan
    return (mean_tm * R * s_over_r / 1000.0) / abs(delta_h_kj_mol)

rows = [
    ("Prediction_probability", "N/A", "%", "ML-model probability cannot be generated by LAMMPS"),
    ("DeltaHmix_elemental_reference", dh_native, "kJ/mol", "LAMMPS alloy energy plus native pure references"),
    ("DeltaHmix_FCC_reference", dh_fcc, "kJ/mol", "LAMMPS alloy energy plus FCC-constrained pure references"),
    ("DeltaRadius", features["atomic_size_difference_delta"]["value"], "%", "formula descriptor"),
    ("Lambda", features["Lambda"]["value"], "dimensionless", "formula descriptor"),
    ("MeanAtomicRadius", features["mean_atomic_radius"]["value"], "pm", "weighted elemental descriptor"),
    ("MeanDensity_formula", features["mean_elemental_density"]["value"], "g/cm3", "weighted elemental descriptor"),
    ("Density_LAMMPS_0K", verification["relaxed_FCC_density"]["value"], "g/cm3", "relaxed simulated density"),
    ("MeanMeltingPoint_descriptor", features["mean_melting_point"]["value"], "K", "weighted descriptor; not simulated melting"),
    ("MixingEntropy_over_R", features["Sconf_over_R"]["value"], "dimensionless", "four active elements; Co fraction is zero"),
    ("MixingEntropy", features["Sconf"]["value"], "J/mol/K", "configurational entropy"),
    ("Omega_native_DH", omega(dh_native), "dimensionless", "uses native-reference DeltaHmix"),
    ("Omega_FCC_DH", omega(dh_fcc), "dimensionless", "uses FCC-reference DeltaHmix"),
    ("VEC", features["VEC"]["value"], "dimensionless", "weighted descriptor"),
    ("Lowest_0K_starting_phase", verification["lowest_ideal_phase"]["value"], "label", "FCC/HCP/BCC screen"),
    ("Lowest_quench_source_T", verification["lowest_quench_source_temperature"]["value"], "K", "lowest quenched 0 K energy"),
]

output = ROOT / "app_feature_simulation_report.csv"
with output.open("w", newline="", encoding="utf-8") as handle:
    writer = csv.writer(handle)
    writer.writerow(["feature", "value", "unit", "source_or_note"])
    writer.writerows(rows)
print(f"Saved {output.name}")
